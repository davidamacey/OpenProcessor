def _entropy_start(data: bytes) -> int:
    """The first byte after the first start-of-scan segment."""
    at = data.index(b'\xff\xda')
    (length,) = struct.unpack('>H', data[at + 2 : at + 4])
    return at + 2 + int(length)


def _scramble(data: bytes) -> bytes:
    """Entropy bytes scrambled without making or breaking a marker: the end marker stays."""
    out = bytearray(data)
    for k in range(_entropy_start(data) + 3, len(data) - 4, 5):
        if 0xFF not in (data[k - 1], data[k], data[k] ^ 0x5A):
            out[k] ^= 0x5A
    return bytes(out)


def _damaged(rgb: Any) -> list[tuple[str, str, bytes, float]]:
    from PIL import Image

    img = Image.fromarray(rgb)
    base = _save(img, 'JPEG', quality=90)
    prog = _save(img, 'JPEG', quality=90, progressive=True)
    png = _save(img, 'PNG')
    cmyk = _save(img.convert('CMYK'), 'JPEG', quality=90)
    scan = _entropy_start(base)
    bad_huffman = _scramble(base)
    dht = base.index(b'\xff\xc4')
    bad_table = bytearray(base)
    bad_table[dht + 5 : dht + 21] = b'\xff' * 16  # code counts past what 16 bits can hold
    out: list[tuple[str, str, bytes, float]] = []
    for gate, suffix in ((SMALL, 'small'), (0.0, 'gpu')):
        out += [
            (f'damaged_truncated_half_{suffix}', 'jpg', base[: len(base) // 2], gate),
            (f'damaged_truncated_after_sos_{suffix}', 'jpg', base[: scan + 4], gate),
            (f'damaged_truncated_no_eoi_{suffix}', 'jpg', base[:-2], gate),
            (f'damaged_bad_huffman_data_{suffix}', 'jpg', bad_huffman, gate),
            (f'damaged_bad_huffman_table_{suffix}', 'jpg', bytes(bad_table), gate),
            (f'damaged_trailing_bytes_{suffix}', 'jpg', base + b'trailer bytes\x00\x01' * 4, gate),
            (f'damaged_trailing_jpeg_{suffix}', 'jpg', base + base, gate),
        ]
    out += [
        ('damaged_cmyk_truncated', 'jpg', cmyk[: len(cmyk) * 2 // 3], 0.0),
        ('damaged_cmyk_bad_huffman_data', 'jpg', _scramble(cmyk), 0.0),
        ('damaged_progressive_truncated', 'jpg', prog[: len(prog) * 2 // 3], 0.0),
        ('damaged_progressive_no_eoi', 'jpg', prog[:-2], 0.0),
        ('damaged_soi_only', 'jpg', b'\xff\xd8', 0.0),
        ('damaged_soi_garbage', 'jpg', b'\xff\xd8\xff\xe0\x00\x02' + b'\x00' * 40, 0.0),
        ('damaged_empty', 'bin', b'', 0.0),
        ('damaged_text', 'bin', b'this is not an image at all\n' * 3, 0.0),
        ('damaged_png_truncated', 'png', png[: len(png) // 2], 0.0),
        ('damaged_png_bad_crc', 'png', png[:-5] + bytes([png[-5] ^ 0xFF]) + png[-4:], 0.0),
        ('damaged_png_bad_idat_crc', 'png', _flip_idat_crc(png), 0.0),
    ]
    return out


def _flip_idat_crc(png: bytes) -> bytes:
    at = png.index(b'IDAT') - 4
    n = struct.unpack('>I', png[at : at + 4])[0]
    crc = at + 8 + n
    return png[:crc] + bytes([png[crc] ^ 0xFF]) + png[crc + 1 :]


def _huge() -> list[tuple[str, str, bytes, float]]:
    """Headers that claim more pixels than the gates allow (the data stops early)."""
    png = (
        b'\x89PNG\r\n\x1a\n'
        + _chunk(b'IHDR', struct.pack('>IIBBBBB', 20000, 20000, 8, 2, 0, 0, 0))
        + _chunk(b'IEND', b'')
    )
    bomb = (
        b'\x89PNG\r\n\x1a\n'
        + _chunk(b'IHDR', struct.pack('>IIBBBBB', 60000, 60000, 8, 2, 0, 0, 0))
        + _chunk(b'IEND', b'')
    )
    return [('huge_png_header', 'png', png, 0.0), ('huge_png_bomb', 'png', bomb, 0.0)]


#: The engine's ceiling for every case (``OP_FRAME_ENGINE_MAX_MEGAPIXELS``'s default).
MAX_MP = 100.0


def _answer(data: bytes, lo: float) -> dict[str, Any]:
    """What the Python engine answers for ``data`` up to the card (``FrameEngine._process``)."""
    from frame_engine import host_decode
    from frame_engine.prep_geometry import route
    from src.domain.decode_route import cpu_reason_route

    r = route(data, lo, MAX_MP)
    if r.kind == 'refused':
        return {'route': 'none', 'status': r.reason}
    if r.kind == 'gpu':
        return {'route': 'gpu', 'status': None}
    out: dict[str, Any] = {'route': cpu_reason_route(r.reason)}
    try:
        width, height = host_decode.probe(data)
    except host_decode.TooLargeError:
        return {'route': 'none', 'status': 'huge'}
    except host_decode.HostDecodeError:
        return {'route': 'none', 'status': 'decoder'}
    if width * height / 1e6 > MAX_MP:
        return {'route': 'none', 'status': 'huge'}
    try:
        rgb = host_decode.decode(data)
    except host_decode.HostDecodeError:
        return {'route': 'none', 'status': 'decoder'}
    if int(rgb.shape[0]) * int(rgb.shape[1]) != width * height:
        return {'route': 'none', 'status': 'decoder'}
    raw = rgb.tobytes()
    out.update(
        status='ok',
        size=[int(rgb.shape[1]), int(rgb.shape[0])],
        sha256=hashlib.sha256(raw).hexdigest(),
    )
    out['_pixels'] = raw
    return out


def render() -> dict[str, bytes]:
    _setup()
    rgb = _pattern()
    cases = _jpeg_cases(rgb) + _png_cases(rgb) + _other_cases(rgb) + _damaged(rgb) + _huge()
    files: dict[str, bytes] = {}
    table = []
    for name, ext, data, lo in cases:
        file = f'{name}.{ext}'
        files[file] = data
        answer = _answer(data, lo)
        if (raw := answer.pop('_pixels', None)) is not None:
            answer['pixels'] = f'{name}.rgb'
            files[answer['pixels']] = raw
        table.append({'name': name, 'file': file, 'min_megapixels': lo,
                      'max_megapixels': MAX_MP, **answer})  # fmt: skip
    files['cases.json'] = (json.dumps(table, indent=1) + '\n').encode()
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='compare with the committed files')
    args = ap.parse_args(argv)
    files = render()
    if args.check:
        stale = [
            n for n, d in files.items() if not (OUT / n).is_file() or (OUT / n).read_bytes() != d
        ]
        extra = sorted(p.name for p in OUT.iterdir() if p.name not in files) if OUT.is_dir() else []
        for n in stale + extra:
            print(f'stale: {n}', file=sys.stderr)
        return 1 if stale or extra else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.iterdir():
        if old.name not in files:
            old.unlink()
    for name, data in files.items():
        (OUT / name).write_bytes(data)
    print(f'wrote {len(files)} files to {OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
