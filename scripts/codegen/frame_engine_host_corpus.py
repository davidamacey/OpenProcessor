#!/usr/bin/env python3
"""The format and damaged-file corpus of the native frame engine's host route (plan 17 N1a).

Builds small generated images, one per accepted Pillow plugin and mode (plus EXIF and XMP
orientations and the damaged files of plan 17 section 1.2: truncated, bad Huffman data, a bad
Huffman table, bytes after the end marker), and records what the Python engine answers for each
without a card: the route of ``prep_geometry.route``, then for a host-route file the steps of
``FrameEngine._source`` and ``_decode_host`` (``host_decode.probe``, the megapixel gate,
``host_decode.decode``, the pixel-count check). A file the route sends to the GPU is recorded with
its route only; its status is the card's (the GPU hold compares it).

Writes under ``native/frame_engine/tests/golden/host/``: each file as it is, and ``cases.json``
(name, file, the megapixel gates, route, status, decoded size, the file ``<name>.rgb`` of the
decoded RGB pixels and their SHA-256). Every image here is generated by this script; nothing is a
photo. The Rust test ``native/frame_engine/tests/golden_host.rs`` reads them. ``--check`` regenerates into memory and
compares with the committed files. Deleted with the Python engine at the switch (plan 17 N3).
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import struct
import sys
import types
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'native' / 'frame_engine' / 'tests' / 'golden' / 'host'
W, H = 23, 15
#: A megapixel floor above every image here, so a clean baseline JPEG routes ``cpu_small``.
SMALL = 1.0


def _setup() -> None:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    sys.modules.setdefault('cupy', types.ModuleType('cupy'))


def _pattern(w: int = W, h: int = H) -> Any:
    import numpy as np

    y, x = np.mgrid[0:h, 0:w]
    rng = np.random.default_rng(20261115)
    noise = rng.integers(0, 48, (h, w, 3))
    rgb = np.stack([x * 255 // max(w - 1, 1), y * 255 // max(h - 1, 1), (x + y) * 7 % 256], -1)
    return np.clip(rgb + noise - 24, 0, 255).astype(np.uint8)


def _cmyk_grid() -> Any:
    """Every (C, K) pair on a step of 5 with M and Y moving the other way, as a CMYK image."""
    import numpy as np
    from PIL import Image

    v = np.arange(0, 256, 5, dtype=np.uint8)
    c, k = np.meshgrid(v, v)
    return Image.fromarray(np.stack([c, 255 - c, k // 2 + c // 2, k], -1).astype(np.uint8), 'CMYK')


def _save(img: Any, fmt: str, **kw: Any) -> bytes:
    buf = io.BytesIO()
    img.save(buf, fmt, **kw)
    return buf.getvalue()


def _exif(orientation: int) -> bytes:
    from PIL import Image

    exif = Image.Exif()
    exif[0x0112] = orientation
    return exif.tobytes()


def _xmp(orientation: int) -> bytes:
    return (
        b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/'
        b'22-rdf-syntax-ns#"><rdf:Description xmlns:tiff="http://ns.adobe.com/tiff/1.0/" '
        b'tiff:Orientation="' + str(orientation).encode() + b'"/></rdf:RDF></x:xmpmeta>'
    )


def _srgb_profile() -> bytes:
    """Little CMS's built-in sRGB with its creation date zeroed, so the file is reproducible."""
    from PIL import ImageCms

    icc = bytearray(ImageCms.ImageCmsProfile(ImageCms.createProfile('sRGB')).tobytes())
    icc[24:36] = bytes(12)
    return bytes(icc)


def _jpeg_cases(rgb: Any) -> list[tuple[str, str, bytes, float]]:
    from PIL import Image

    img = Image.fromarray(rgb)
    grey = img.convert('L')
    out: list[tuple[str, str, bytes, float]] = [
        ('jpeg_baseline_420_small', 'jpg', _save(img, 'JPEG', quality=90), SMALL),
        ('jpeg_baseline_444_small', 'jpg', _save(img, 'JPEG', quality=90, subsampling=0), SMALL),
        ('jpeg_baseline_422_small', 'jpg', _save(img, 'JPEG', quality=90, subsampling=1), SMALL),
        ('jpeg_baseline_grey_small', 'jpg', _save(grey, 'JPEG', quality=90), SMALL),
        ('jpeg_baseline_gpu', 'jpg', _save(img, 'JPEG', quality=90), 0.0),
        ('jpeg_progressive', 'jpg', _save(img, 'JPEG', quality=90, progressive=True), 0.0),
        ('jpeg_progressive_grey', 'jpg', _save(grey, 'JPEG', progressive=True), 0.0),
        ('jpeg_cmyk', 'jpg', _save(img.convert('CMYK'), 'JPEG', quality=90), 0.0),
        ('jpeg_cmyk_grid', 'jpg', _save(_cmyk_grid(), 'JPEG', quality=100, subsampling=0), 0.0),
        (
            'jpeg_cmyk_progressive',
            'jpg',
            _save(img.convert('CMYK'), 'JPEG', quality=90, progressive=True),
            0.0,
        ),
        (
            'jpeg_srgb_profile_small',
            'jpg',
            _save(
                img,
                'JPEG',
                quality=90,
                icc_profile=_srgb_profile(),
            ),
            SMALL,
        ),
    ]
    out += [
        (f'jpeg_exif_orientation_{o}', 'jpg', _save(img, 'JPEG', exif=_exif(o)), SMALL)
        for o in range(1, 9)
    ]
    out += [
        (f'jpeg_xmp_orientation_{o}', 'jpg', _save(img, 'JPEG', xmp=_xmp(o)), SMALL) for o in (3, 6)
    ]
    out.append(('jpeg_exif_orientation_9', 'jpg', _save(img, 'JPEG', exif=_exif(9)), SMALL))
    return out


def _png_cases(rgb: Any) -> list[tuple[str, str, bytes, float]]:
    import numpy as np
    from PIL import Image

    img = Image.fromarray(rgb)
    alpha = Image.fromarray(
        (np.arange(W * H, dtype=np.uint32).reshape(H, W) * 37 % 256).astype(np.uint8)
    )
    rgba = img.copy()
    rgba.putalpha(alpha)
    la = img.convert('L')
    la.putalpha(alpha)
    pal = img.quantize(16)
    pal_t = pal.copy()
    pal_t.info['transparency'] = 3
    grey16 = Image.fromarray(rgb[..., 0].astype(np.uint16) * 257 - rgb[..., 1].astype(np.uint16))
    rgb16 = rgb.astype('>u2') * 251 + rgb[..., ::-1].astype('>u2')
    png16 = _png_raw(rgb16.astype('>u2').tobytes(), W, H, 16, 2)
    rgba16 = np.concatenate([rgb16, rgb16[..., :1]], -1).astype('>u2')
    png16a = _png_raw(rgba16.tobytes(), W, H, 16, 6)
    return [
        ('png_rgb', 'png', _save(img, 'PNG'), 0.0),
        ('png_rgba', 'png', _save(rgba, 'PNG'), 0.0),
        ('png_l', 'png', _save(img.convert('L'), 'PNG'), 0.0),
        ('png_la', 'png', _save(la, 'PNG'), 0.0),
        ('png_p', 'png', _save(pal, 'PNG'), 0.0),
        ('png_p_transparency', 'png', _save(pal_t, 'PNG', transparency=3), 0.0),
        ('png_1bit', 'png', _save(img.convert('1'), 'PNG'), 0.0),
        ('png_grey16', 'png', _save(grey16, 'PNG'), 0.0),
        ('png_grey16_trns', 'png', _save(grey16, 'PNG', transparency=300), 0.0),
        ('png_rgb16', 'png', png16, 0.0),
        ('png_rgba16', 'png', png16a, 0.0),
        ('png_interlaced', 'png', _png_interlaced(rgb), 0.0),
        ('png_exif_orientation_6', 'png', _save(img, 'PNG', exif=_exif(6)), 0.0),
        ('png_exif_orientation_3', 'png', _save(img, 'PNG', exif=_exif(3)), 0.0),
    ]


def _chunk(kind: bytes, payload: bytes) -> bytes:
    import zlib

    body = kind + payload
    return struct.pack('>I', len(payload)) + body + struct.pack('>I', zlib.crc32(body))


def _png_raw(raw: bytes, w: int, h: int, depth: int, colour: int, interlace: int = 0) -> bytes:
    """A PNG written field by field (Pillow does not write 16-bit RGB or Adam7)."""
    import zlib

    row = len(raw) // h
    data = b''.join(b'\0' + raw[y * row : (y + 1) * row] for y in range(h))
    return (
        b'\x89PNG\r\n\x1a\n'
        + _chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, depth, colour, 0, 0, interlace))
        + _chunk(b'IDAT', zlib.compress(data))
        + _chunk(b'IEND', b'')
    )


def _png_interlaced(rgb: Any) -> bytes:
    """Adam7: each pass's rows, filter 0, in the PNG specification's pass order."""
    import zlib

    passes = [
        (0, 0, 8, 8),
        (4, 0, 8, 8),
        (0, 4, 4, 8),
        (2, 0, 4, 4),
        (0, 2, 2, 4),
        (1, 0, 2, 2),
        (0, 1, 1, 2),
    ]
    data = b''
    for x0, y0, dx, dy in passes:
        sub = rgb[y0::dy, x0::dx]
        if sub.size == 0:
            continue
        data += b''.join(b'\0' + bytes(r.tobytes()) for r in sub)
    return (
        b'\x89PNG\r\n\x1a\n'
        + _chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 1))
        + _chunk(b'IDAT', zlib.compress(data))
        + _chunk(b'IEND', b'')
    )


